"""
放弃自造判据。改用"同源比对 + 受控对照"：
 方法：把 0x00000（确证真代码，含 YELSTO 分区表）与 0x1E000 一起，
       在"随机数据"（os.urandom 同长度）与"已知文本"（python 源码）上做同一套度量，
       看哪些度量的值在两个极端之间"有梯度"——只有有梯度的度量才能用作判据。

度量集合（每个都算梯度）：
  M1 字节熵
  M2 零占比
  M3 相邻字节差值 = 0 的占比 (delta-0 rate)
  M4 16 位 u16 高频前 20 覆盖率
  M5 顺序 8051 解码的"平均指令长度"
  M6 顺序 8051 解码里 3 字节指令(LJMP/LCALL)占比
  M7 顺序 8051 解码里 "单字节无操作数指令"占比
  M8 顺序 8051 解码里 操作数字节 与 操作码字节 的熵差
"""
