LEN = build_len()

def metrics(b, nm):
    n = len(b)
    m = {}
    m["熵"] = H(b)
    m["零占比"] = b.count(0)/n
    m["delta0"] = sum(1 for i in range(n-1) if b[i+1] == b[i])/(n-1)
    c16 = collections.Counter(int.from_bytes(b[i:i+2], "little") for i in range(0, n-1, 2))
    m["u16top20"] = sum(v for _, v in c16.most_common(20))/max(1, len(c16))
    # 顺序 8051 解码
    i = 0; lens = []
    while i < n:
        step = LEN[b[i]]
        if i + step > n: break
        lens.append(step); i += step
    cov = i/n
    if lens:
        avg = sum(lens)/len(lens)
        l3 = sum(1 for x in lens if x == 3)/len(lens)
        l1 = sum(1 for x in lens if x == 1)/len(lens)
    else:
        avg = l3 = l1 = 0.0
    m["8051覆盖"] = cov
    m["平均指令长"] = avg
    m["3字节占比"] = l3
    m["1字节占比"] = l1
    # 操作码 vs 操作数 熵差
    opsb = bytearray(); opdb = bytearray()
    i = 0
    while i < n:
        step = LEN[b[i]]
        if i + step > n: break
        opsb.append(b[i]); opdb.extend(b[i+1:i+step]); i += step
    m["op数熵差"] = H(bytes(opsb)) - H(bytes(opdb)) if opdb else 0.0
    w("  %-30s" % nm)
    for k, v in m.items():
        w("      %-10s %.4f" % (k, v))
    return m

