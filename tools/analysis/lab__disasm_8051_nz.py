"""排除 0 填充后的 8051 指令分布 —— 判断 GT7868Q 主体是否标准 Turbo-51 代码。

第一轮统计被 0 填充（14.82%）污染：NOP 占 20.70%。
本轮：只统计「非 0 起始」的指令，并与「真 8051 代码应有的分布」对比。

真 8051（Keil C51 典型输出）期望：
  NOP 极少(<0.5%) · MOV 系占大头(30-45%) · LCALL/ACALL 常见 · RET/RETI 常见(3-8%)
  PUSH/POP 成对 · MOVX 在带 xdata 的设计里常见 · LJMP 少(仅跨 bank)
"""
import os
import collections
import re

HERE = r"<LAB>\touchpad-lab\poc\anchor-hunt"
d = open(os.path.join(HERE, "GT7868Q_plain.bin"), "rb").read()
seg = d[0x1200:0x19800]

# 直接复用前一个脚本的长度表思路（简化版：只按字节分类，不做模板）
THREE = {0x02, 0x12, 0x90, 0x75, 0x85, 0x43, 0x53, 0x63, 0xB5, 0xD5,
         0xB4, 0xB6, 0xB7, 0xB8, 0xB9, 0xBA, 0xBB, 0xBC, 0xBD, 0xBE, 0xBF,
         0x10, 0x20, 0x30}
TWO = set(range(0x00, 0x100)) - THREE
TWO -= {0x00, 0x03, 0x04, 0x13, 0x14, 0x23, 0x24, 0x33, 0x34, 0x73, 0x83, 0x93,
        0xA3, 0xB3, 0xC3, 0xD3, 0xE0, 0xE2, 0xE3, 0xE4, 0xF0, 0xF2, 0xF3, 0xF4,
        0x22, 0x32, 0x84, 0xA4, 0xC4, 0xD4, 0x44, 0x54, 0x64, 0x74, 0x94, 0x24,
        0x34, 0x05, 0x15, 0x25, 0x35, 0x45, 0x55, 0x65, 0x95, 0xB5, 0xC5, 0xD5,
        0xE5, 0xF5, 0x76, 0x77, 0x86, 0x87, 0xA6, 0xA7, 0xC6, 0xC7, 0xD6, 0xD7,
        0xE6, 0xE7, 0xF6, 0xF7, 0x06, 0x16, 0x26, 0x36, 0x46, 0x56, 0x66}
for h in range(16):
    TWO.discard((h * 0x10 + 1) & 0xFF)
TWO |= {0x74, 0x24, 0x34, 0x44, 0x54, 0x64, 0x94, 0xE5, 0xF5, 0x05, 0x15,
        0x25, 0x35, 0x45, 0x55, 0x65, 0x95, 0xC5, 0xE6, 0xE7, 0xF6, 0xF7,
        0x06, 0x16, 0x76, 0x77, 0x86, 0x87, 0xA6, 0xA7, 0xC6, 0xC7, 0xD6, 0xD7,
        0x26, 0x36, 0x46, 0x56, 0x66, 0x42, 0x52, 0x62, 0x72, 0x82, 0x92, 0xA2,
        0xB2, 0xC2, 0xD2, 0x40, 0x50, 0x60, 0x70, 0x80, 0x88, 0x89, 0x8A, 0x8B,
        0x8C, 0x8D, 0x8E, 0x8F, 0x98, 0x99, 0x9A, 0x9B, 0x9C, 0x9D, 0x9E, 0x9F,
        0xC0, 0xD0, 0xB0, 0xA0, 0x90}
for op in (0x78, 0x79, 0x7A, 0x7B, 0x7C, 0x7D, 0x7E, 0x7F):
    TWO.add(op)
for op in (0xD8, 0xD9, 0xDA, 0xDB, 0xDC, 0xDD, 0xDE, 0xDF):
    TWO.add(op)
for op in (0xA8, 0xA9, 0xAA, 0xAB, 0xAC, 0xAD, 0xAE, 0xAF):
    TWO.add(op)
for op in (0xC8, 0xC9, 0xCA, 0xCB, 0xCC, 0xCD, 0xCE, 0xCF):
    TWO.add(op)
for op in (0xE8, 0xE9, 0xEA, 0xEB, 0xEC, 0xED, 0xEE, 0xEF):
    TWO.add(op)
for op in (0xF8, 0xF9, 0xFA, 0xFB, 0xFC, 0xFD, 0xFE, 0xFF):
    TWO.add(op)
TWO -= THREE


def ln(op):
    return 3 if op in THREE else (2 if op in TWO else 1)


def scan(seg, skip_zero_starts=True):
    cnt = collections.Counter()
    nins = 0
    p = 0
    while p < len(seg):
        op = seg[p]
        if not (skip_zero_starts and op == 0x00):
            cnt[op] += 1
            nins += 1
        p += ln(op)
    return cnt, nins


cnt, nins = scan(seg)
print("=" * 100)
print("① 排除 0 起始后的操作码分布（共 %d 条指令）" % nins)
print("=" * 100)
print("  %-24s %-10s %-12s %s" % ("操作码", "次数", "占比", "真 8051 期望"))
EXPECT = {
    0x02: "极少(跨 bank 才用)", 0x12: "常见(函数调用)", 0x22: "常见(函数返回)",
    0x32: "偶见(中断返回)", 0x74: "很常见", 0x75: "极常见", 0xE5: "很常见",
    0xF5: "很常见", 0x05: "常见", 0x15: "常见", 0x90: "常见(加载 DPTR)",
    0xE0: "常见(读 xdata)", 0xF0: "常见(写 xdata)", 0x80: "常见(短跳)",
    0xA3: "常见(INC DPTR)", 0x00: "极少",
}
for op, c in cnt.most_common(22):
    print("  0x%02X %-19s %-10d %-12s %s" % (
        op, "", c, "%.2f%%" % (100 * c / nins), EXPECT.get(op, "")))
print()

print("=" * 100)
print("② 关键操作码对照")
print("=" * 100)
key = [(0x22, "RET"), (0x32, "RETI"), (0x02, "LJMP"), (0x12, "LCALL"),
       (0x74, "MOV A,#imm"), (0x75, "MOV direct,#imm"), (0xE5, "MOV A,direct"),
       (0xF5, "MOV direct,A"), (0x90, "MOV DPTR,#imm16"), (0xC0, "PUSH direct"),
       (0xD0, "POP direct"), (0x00, "NOP"), (0x80, "SJMP")]
for op, name in key:
    c = cnt.get(op, 0)
    print("  0x%02X %-20s %6d  (%.3f%%)" % (op, name, c, 100 * c / nins))
print()

print("=" * 100)
print("③ PUSH/POP 配对检验（真代码应大致成对）")
print("=" * 100)
pu, po = cnt.get(0xC0, 0), cnt.get(0xD0, 0)
print("  PUSH(push direct) %d  vs  POP(pop direct) %d   比值 %.2f" % (
    pu, po, pu / max(1, po)))
print("  （真代码：比值 ≈ 1.0；若严重失衡 ⇒ 非标准编译器输出）")
print()

print("=" * 100)
print("④ RET 密度检验")
print("=" * 100)
rt = cnt.get(0x22, 0)
print("  RET 共 %d 条，占 %.3f%%" % (rt, 100 * rt / nins))
print("  若主体是代码，函数数 ≈ RET 数；按每函数 40-80 字节估算，代码量 ≈ %d - %d 字节" % (
    rt * 40, rt * 80))
print("  实际主体长度 = %d 字节" % len(seg))
print()

print("=" * 100)
print("⑤ 最长连续「合理指令」序列（启发式：不含 NOP/未定义/低频异常码）")
print("=" * 100)
BAD = {0x00, 0xA5, 0xA0, 0x9F, 0x9D, 0x97}
runs = []
cur = 0
p = 0
while p < len(seg):
    op = seg[p]
    if op in BAD:
        if cur > 0:
            runs.append(cur)
        cur = 0
    else:
        cur += 1
    p += ln(op)
runs.sort(reverse=True)
print("  最长 %d 条；Top 10 长度: %s" % (len(runs), runs[:10]))
print("  平均连续长度 %.1f 条" % (sum(runs) / max(1, len(runs))))
